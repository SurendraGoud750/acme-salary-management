require "securerandom"

departments = %w[Engineering Product Finance People Sales Operations Legal Marketing Support]
Department.insert_all!(departments.map { |name| { name: name, created_at: Time.current, updated_at: Time.current } }, unique_by: :name)
department_ids = Department.order(:id).pluck(:id)
countries = %w[IN US GB DE CA AU SG NL FR JP]
first_names = %w[Aarav Aditi Arjun Anaya Dev Diya Ishaan Kavya Liam Maya Noah Olivia Rohan Sara Theo Zara]
last_names = %w[Sharma Patel Singh Gupta Mehta Brown Wilson Taylor Martin Clark Lewis Walker Hall Young]
currencies = { "IN" => "INR", "US" => "USD", "GB" => "GBP", "DE" => "EUR", "CA" => "CAD", "AU" => "AUD", "SG" => "SGD", "NL" => "EUR", "FR" => "EUR", "JP" => "USD" }
base = Date.new(2022, 1, 1)
now = Time.current

# Synthetic, deterministic employee data. IDs are generated by the database.
Employee.delete_all
SalaryRecord.delete_all
batch = []
salary_batch = []
10_000.times do |i|
  country = countries[i % countries.length]
  first = first_names[(i * 7) % first_names.length]
  last = last_names[(i * 11) % last_names.length]
  status = i % 31 == 0 ? "inactive" : (i % 47 == 0 ? "on_leave" : "active")
  batch << {
    employee_number: format("EMP-%05d", i + 1), first_name: first, last_name: "#{last}#{i % 9 == 0 ? "son" : ""}",
    email: "employee#{i + 1}@acme.example", department_id: department_ids[i % department_ids.length],
    country_code: country, employment_status: status, created_at: now, updated_at: now
  }
end
batch.each_slice(1000) do |slice|
  Employee.insert_all!(slice)
end
employees = Employee.order(:employee_number).pluck(:id, :employee_number, :country_code)
employees.each_with_index do |(id, number, country), i|
  salary = 42_000 + ((i * 137) % 98_000)
  salary_batch << { employee_id: id, amount: salary, currency: currencies.fetch(country, "USD"),
    pay_frequency: i % 12 == 0 ? "monthly" : "annual", effective_from: base + (i % 900), effective_to: nil,
    created_at: now, updated_at: now }
end
salary_batch.each_slice(1000) { |slice| SalaryRecord.insert_all!(slice) }
puts "Seeded #{Employee.count} employees and #{SalaryRecord.count} current salary records."
